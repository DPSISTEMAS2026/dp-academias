create policy material_progress_all on public.material_progress for all using (true) with check (true);
grant all on public.material_progress to anon, authenticated;

create table if not exists public.events (
  id text primary key,
  slug text not null unique,
  title text not null,
  description text default '',
  photo text default '',
  rules_url text default '',
  rules_name text default '',
  event_date text,
  start_time text default '',
  end_time text default '',
  address text default '',
  capacity integer,
  paid boolean default true,
  price integer default 0,
  status text default 'draft',
  categories jsonb default '[]'::jsonb,
  created_at timestamptz default now()
);

create table if not exists public.event_registrations (
  id text primary key,
  event_id text not null references public.events(id) on delete cascade,
  kind text not null default 'guest',
  student_id text,
  name text not null,
  email text,
  phone text,
  document_id text,
  birth_date text,
  age integer,
  weight numeric,
  gender text,
  belt text,
  academy text,
  category_id text,
  category_name text,
  amount integer default 0,
  status text default 'pending',
  method text,
  created_at timestamptz default now()
);

create unique index if not exists event_reg_student_unique
  on public.event_registrations (event_id, student_id)
  where student_id is not null;

alter table public.events enable row level security;
alter table public.event_registrations enable row level security;
drop policy if exists events_all on public.events;
drop policy if exists event_registrations_all on public.event_registrations;
create policy events_all on public.events for all using (true) with check (true);
create policy event_registrations_all on public.event_registrations for all using (true) with check (true);
grant all on public.events to anon, authenticated;
grant all on public.event_registrations to anon, authenticated;

