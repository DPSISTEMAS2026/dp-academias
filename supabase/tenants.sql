create table if not exists public.academias (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  custom_domain text unique,
  name text not null,
  logo_url text default '',
  color text default '#006970',
  status text default 'active',
  max_students integer default 120,
  max_news integer default 40,
  max_gallery integer default 30,
  created_at timestamptz default now()
);

alter table public.sedes add column if not exists academia_id bigint references public.academias(id) on delete cascade;
alter table public.admins add column if not exists academia_id bigint references public.academias(id) on delete cascade;
