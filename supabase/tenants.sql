alter table public.attendance add column if not exists academia_id bigint references public.academias(id) on delete cascade;
alter table public.material_progress add column if not exists academia_id bigint references public.academias(id) on delete cascade;
alter table public.events add column if not exists academia_id bigint references public.academias(id) on delete cascade;
alter table public.event_registrations add column if not exists academia_id bigint references public.academias(id) on delete cascade;

alter table public.admins drop constraint if exists admins_email_key;
create unique index if not exists admins_academia_email on public.admins (academia_id, lower(email));
create unique index if not exists students_academia_email on public.students (academia_id, lower(email)) where email is not null and email <> '';

alter table public.events drop constraint if exists events_slug_key;
create unique index if not exists events_academia_slug on public.events (academia_id, slug);

create index if not exists students_academia_id on public.students (academia_id);
create index if not exists sedes_academia_id on public.sedes (academia_id);
create index if not exists news_academia_id on public.news (academia_id);
create index if not exists class_slots_academia_id on public.class_slots (academia_id);

create table if not exists public.academy_media (
  id text primary key,
  academia_id bigint not null references public.academias(id) on delete cascade,
  cf_id text not null,
  url text not null,
  kind text default 'image',
  bytes bigint not null default 0,
  created_at timestamptz default now()
);
